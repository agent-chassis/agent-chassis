export const BACKEND_REFUSAL_TO_DISPATCH_BLOCKER = Object.freeze(
  Object.fromEntries(
    Object.values(BACKEND_REFUSAL_CODES).map((code) => {
      if (!isRuntimeBlockerCode(code)) {
        throw new Error(
          `backend refusal identity ${String(code)} is not a registered runtime blocker code`
        );
      }
      return [code, code];
    })
  )
);

