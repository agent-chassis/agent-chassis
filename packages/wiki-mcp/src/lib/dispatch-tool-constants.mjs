const RETIRED_DISPATCH_BLOCKER_CODE_SET = new Set(RETIRED_DISPATCH_BLOCKER_CODE_IDENTITIES);
for (const [mapName, map] of [
  ["DISPATCH_BLOCKER_CODES", DISPATCH_BLOCKER_CODES],
  ["DISPATCH_MECHANICAL_BLOCKER_CODES", DISPATCH_MECHANICAL_BLOCKER_CODES]
]) {
  for (const [key, code] of Object.entries(map)) {
    if (!isRuntimeBlockerCode(code)) {
      throw new Error(
        `${mapName}.${key} is not a registered runtime blocker code: ${String(code)}`
      );
    }
    if (RETIRED_DISPATCH_BLOCKER_CODE_SET.has(code)) {
      throw new Error(`${mapName}.${key} names retired runtime blocker identity ${code}`);
    }
  }
}
for (const code of DISPATCH_GRAPH_BLOCKER_CODE_VALUES) {
  if (!isRuntimeBlockerCode(code)) {
    throw new Error(`DISPATCH_GRAPH_BLOCKER_CODE_VALUES names an unregistered code: ${String(code)}`);
  }
}
for (const code of RETIRED_DISPATCH_BLOCKER_CODE_IDENTITIES) {
  if (isRuntimeBlockerCode(code)) {
    throw new Error(
      `retired runtime blocker identity ${code} is registered in the active taxonomy again`
    );
  }
}
